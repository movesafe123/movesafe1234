-- 1. BẢNG TRẠM SẠC XE ĐIỆN (EV STATIONS)
-- ------------------------------------------------------------------------------------
DROP TABLE IF EXISTS ev_stations CASCADE;
CREATE TABLE ev_stations (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(255) NOT NULL,
    provider VARCHAR(100), -- Ví dụ: VinFast, ChargeAlong, EVOne
    address TEXT,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    capacity INT DEFAULT 1, -- Số cổng sạc
    is_active BOOLEAN DEFAULT true,
    location GEOGRAPHY(Point, 4326) -- Tọa độ chuẩn hệ quy chiếu toàn cầu
);

-- Tự động tính toán cột 'location' dựa vào 'lat' và 'lng'
CREATE OR REPLACE FUNCTION update_ev_location()
RETURNS TRIGGER AS $$
BEGIN
  NEW.location = ST_SetSRID(ST_MakePoint(NEW.lng, NEW.lat), 4326);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_update_ev_location
BEFORE INSERT OR UPDATE ON ev_stations
FOR EACH ROW EXECUTE FUNCTION update_ev_location();

