-- 2. BẢNG LƯU TRỮ LỊCH SỬ GIAO THÔNG (Lưu 7 ngày)
-- ------------------------------------------------------------------------------------
-- 2. BẢNG LƯU TRỮ LỊCH SỬ GIAO THÔNG (Lưu 7 ngày)
