-- 1. BẢNG LƯU TRỮ LỊCH SỬ NGẬP LỤT ĐÔ THỊ (Cửa sổ trượt 7 ngày)
CREATE TABLE IF NOT EXISTS flood_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id VARCHAR(100) NOT NULL,
    station_name VARCHAR(255) NOT NULL,
    city VARCHAR(50) NOT NULL,
    depth_cm INT NOT NULL,
    danger_level VARCHAR(50) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_flood_history_time ON flood_history(recorded_at);

-- 2. ĐẢM BẢO BẢNG TRAFFIC_HISTORY CÓ SẴN
CREATE TABLE IF NOT EXISTS traffic_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id VARCHAR(100) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    speed_kmh INT,
    congestion_level INT CHECK (congestion_level >= 0 AND congestion_level <= 5),
    weather_condition VARCHAR(50)
);
CREATE INDEX IF NOT EXISTS idx_traffic_history_time ON traffic_history(recorded_at);

-- 3. HÀM TỰ ĐỘNG DỌN DẸP LỊCH SỬ CŨ HƠN 7 NGÀY (Chống tràn dung lượng 500MB)
CREATE OR REPLACE FUNCTION clean_old_urban_history()
RETURNS void AS $$
BEGIN
    DELETE FROM traffic_history WHERE recorded_at < NOW() - INTERVAL '7 days';
    DELETE FROM flood_history WHERE recorded_at < NOW() - INTERVAL '7 days';
END;
$$ LANGUAGE plpgsql;

